import { describe, test, expect } from 'vitest';
import {
  parseDate,
  isWeekend,
  isHoliday,
  calculateDeadline,
  getNotificationDate,
  isInDebtCollectionHolidays,
  daysUntil,
} from './deadline.js';

// Короткая запись даты: d('2026-11-23') вместо new Date(2026, 10, 23)
const d = parseDate;

describe('isWeekend — выходные (ваш код, урок 2)', () => {
  test('суббота и воскресенье — выходные', () => {
    expect(isWeekend(d('2026-11-21'))).toBe(true); // суббота
    expect(isWeekend(d('2026-11-22'))).toBe(true); // воскресенье
  });

  test('понедельник и пятница — рабочие дни', () => {
    expect(isWeekend(d('2026-11-23'))).toBe(false);
    expect(isWeekend(d('2026-11-27'))).toBe(false);
  });
});

describe('isHoliday — праздники во всей Швейцарии', () => {
  test('Новый год, 1 августа и Рождество', () => {
    expect(isHoliday(d('2027-01-01'))).toBe(true);
    expect(isHoliday(d('2026-08-01'))).toBe(true);
    expect(isHoliday(d('2026-12-25'))).toBe(true);
  });

  test('Вознесение 2026 — 14 мая (считается от Пасхи)', () => {
    expect(isHoliday(d('2026-05-14'))).toBe(true);
  });

  test('обычный день — не праздник', () => {
    expect(isHoliday(d('2026-11-23'))).toBe(false);
  });
});

describe('calculateDeadline — 10 дней и перенос на рабочий день', () => {
  test('обычный случай: 27.10 + 10 = пятница 06.11', () => {
    expect(calculateDeadline(d('2026-10-27'))).toEqual(d('2026-11-06'));
  });

  test('10-й день — суббота → понедельник (ваш пример из урока 2)', () => {
    expect(calculateDeadline(d('2026-10-07'))).toEqual(d('2026-10-19'));
  });

  test('Рождество + выходные: 15.12 → понедельник 28.12', () => {
    expect(calculateDeadline(d('2026-12-15'))).toEqual(d('2026-12-28'));
  });
});

describe('getNotificationDate — фикция вручения (ваш код, ст. 85 StPO)', () => {
  test('без извещения — дата получения', () => {
    expect(getNotificationDate(d('2026-11-16'), null)).toEqual(d('2026-11-16'));
  });

  test('забрал поздно: извещение 04.11 + 7 = 11.11 раньше, чем 16.11', () => {
    expect(getNotificationDate(d('2026-11-16'), d('2026-11-04'))).toEqual(d('2026-11-11'));
  });

  test('забрал быстро: 16.11 раньше, чем извещение 14.11 + 7 = 21.11', () => {
    expect(getNotificationDate(d('2026-11-16'), d('2026-11-14'))).toEqual(d('2026-11-16'));
  });

  test('полный путь: извещение 04.11, забрал 16.11 → последний день 23.11', () => {
    const start = getNotificationDate(d('2026-11-16'), d('2026-11-04'));
    expect(calculateDeadline(start)).toEqual(d('2026-11-23'));
  });
});

describe('isInDebtCollectionHolidays — Betreibungsferien (ст. 56 SchKG)', () => {
  test('20 декабря — каникулы, 10 октября — нет', () => {
    expect(isInDebtCollectionHolidays(d('2026-12-20'))).toBe(true);
    expect(isInDebtCollectionHolidays(d('2026-10-10'))).toBe(false);
  });

  test('15–31 июля — каникулы', () => {
    expect(isInDebtCollectionHolidays(d('2026-07-20'))).toBe(true);
  });
});

describe('daysUntil — сколько дней осталось', () => {
  // Второй параметр — «сегодня». Передаём его явно, чтобы тест
  // давал один и тот же результат в любой день.
  test('от 23.11 до 26.11 — 3 дня', () => {
    expect(daysUntil(d('2026-11-26'), d('2026-11-23'))).toBe(3);
  });

  test('прошедшая дата — отрицательное число', () => {
    expect(daysUntil(d('2026-11-20'), d('2026-11-23'))).toBe(-3);
  });
});

